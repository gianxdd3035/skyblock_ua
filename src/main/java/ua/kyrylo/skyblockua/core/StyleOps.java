package ua.kyrylo.skyblockua.core;

/*
 * Операції над стилем, які потрібні рушію перекладу.
 * Рушій нічого не знає про Minecraft: усе, що стосується справжнього Style,
 * реалізує McStyleOps, а тести підставляють свою просту реалізацію.
 */
public interface StyleOps<S> {

    /*
     * Застосувати legacy-код (символ після §) до стилю, як це робить Minecraft:
     * код кольору скидає жирність/курсив тощо, r скидає все, k/l/m/n/o додають формат.
     * Клік і ховер мають зберігатися.
     */
    S applyCode(S base, char code);

    /* Перетворити стиль назад на §-коди (для файлу неперекладених рядків). */
    String legacy(S style);

    /* Чи мають два стилі однакові клік/ховер/вставку. */
    boolean sameExtras(S a, S b);
}
